    def test_merge_chunk_summaries_batches_large_inputs(self) -> None:
        summary = {
            "one_sentence_summary": "一句话总结",
            "main_question": "主要问题",
            "core_viewpoints": [{"point": "观点", "evidence_or_examples": ["例子"]}],
            "important_concepts": ["概念"],
            "data_facts_quotes": ["事实"],
            "outline": ["大纲"],
            "takeaways": ["要点一", "要点二", "要点三"],
            "insufficient_evidence": [],
        }
        chunk_summaries = [
            {**summary, "one_sentence_summary": f"分段 {index}"}
            for index in range(8)
        ]

        with tempfile.TemporaryDirectory() as temp_name:
            temp_dir = Path(temp_name)
            prompts: list[str] = []

            def fake_codex_step(**kwargs):
                prompts.append(kwargs["prompt"])
                return {**summary, "one_sentence_summary": f"合并 {len(prompts)}"}

            with patch.object(module, "run_codex_json_step", side_effect=fake_codex_step):
                result = module.merge_chunk_summaries(
                    codex_path="/usr/bin/codex",
                    chunk_summaries=chunk_summaries,
                    temp_dir=temp_dir,
                    model=None,
                    merge_batch_size=3,
                    reasoning_effort=None,
                )

        self.assertEqual("合并 4", result["one_sentence_summary"])
        self.assertEqual(4, len(prompts))
        self.assertTrue(all("分段结构化摘要 JSON" in prompt for prompt in prompts))

