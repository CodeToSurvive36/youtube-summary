    def test_ensure_codex_cli_skips_broken_path_candidate(self) -> None:
        with tempfile.TemporaryDirectory() as temp_name:
            temp_dir = Path(temp_name)
            broken = temp_dir / "broken-codex"
            fallback = temp_dir / "fallback-codex"
            broken.write_text("#!/bin/sh\nexit 1\n", encoding="utf-8")
            fallback.write_text("#!/bin/sh\necho codex-cli test\nexit 0\n", encoding="utf-8")
            broken.chmod(0o755)
            fallback.chmod(0o755)

            with patch.object(module.shutil, "which", return_value=str(broken)):
                with patch.object(module, "BUNDLED_CODEX_CANDIDATES", [fallback]):
                    self.assertEqual(str(fallback), module.ensure_codex_cli())

