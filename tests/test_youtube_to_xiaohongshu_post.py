    def test_schemas_encode_required_output_counts(self) -> None:
        structured_schema = json.loads(STRUCTURED_SCHEMA_PATH.read_text(encoding="utf-8"))
        post_schema = json.loads(POST_SCHEMA_PATH.read_text(encoding="utf-8"))

        self.assertIn("one_sentence_summary", structured_schema["required"])
        self.assertEqual(3, structured_schema["properties"]["takeaways"]["minItems"])
        self.assertEqual(3, structured_schema["properties"]["takeaways"]["maxItems"])
        self.assertEqual(5, structured_schema["properties"]["core_viewpoints"]["maxItems"])
        self.assertEqual(220, structured_schema["properties"]["one_sentence_summary"]["maxLength"])
        self.assertEqual(260, structured_schema["properties"]["main_question"]["maxLength"])
        viewpoint_schema = structured_schema["properties"]["core_viewpoints"]["items"]
        self.assertEqual(220, viewpoint_schema["properties"]["point"]["maxLength"])
        self.assertEqual(4, viewpoint_schema["properties"]["evidence_or_examples"]["maxItems"])
        self.assertEqual(12, structured_schema["properties"]["important_concepts"]["maxItems"])
        self.assertEqual(12, structured_schema["properties"]["data_facts_quotes"]["maxItems"])
        self.assertEqual(12, structured_schema["properties"]["outline"]["maxItems"])
        self.assertEqual(8, structured_schema["properties"]["insufficient_evidence"]["maxItems"])

        title_groups = post_schema["properties"]["title_groups"]
        self.assertEqual(
            ["pain_point", "counterintuitive", "audience", "viewpoint"],
            title_groups["required"],
        )
        for group_name in title_groups["required"]:
            self.assertEqual(2, title_groups["properties"][group_name]["minItems"])
            self.assertEqual(2, title_groups["properties"][group_name]["maxItems"])
            self.assertEqual(24, title_groups["properties"][group_name]["items"]["maxLength"])
        self.assertEqual(5, post_schema["properties"]["cover_lines"]["minItems"])
        self.assertEqual(5, post_schema["properties"]["cover_lines"]["maxItems"])
        self.assertEqual(600, post_schema["properties"]["body"]["minLength"])
        self.assertEqual(900, post_schema["properties"]["body"]["maxLength"])
        self.assertEqual(8, post_schema["properties"]["tags"]["minItems"])
        self.assertEqual(12, post_schema["properties"]["tags"]["maxItems"])
        self.assertEqual(5, post_schema["properties"]["fact_check"]["minItems"])
        self.assertEqual(8, post_schema["properties"]["fact_check"]["maxItems"])


